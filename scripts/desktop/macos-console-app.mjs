#!/usr/bin/env node
/**
 * 为 macOS 生成/更新 ~/Applications/REALM Console.app。
 *
 * 该 .app 是一个极小的 wrapper：启动后调用 node launcher/realm-console.mjs，
 * 并自动打开浏览器控制台页面。退出 .app（Dock/Command-Tab/Spotlight 中右键退出）
 * 会发送 SIGTERM 给 realm-console.mjs，后者默认停止本地服务。
 *
 * 这样玩家第一次运行安装命令后，以后可以直接从 Spotlight 搜索 "REALM" 启动。
 */
import { existsSync } from "node:fs";
import { mkdir, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

function plist({ bundleId, name, executable }) {
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleExecutable</key>
  <string>${executable}</string>
  <key>CFBundleIdentifier</key>
  <string>${bundleId}</string>
  <key>CFBundleName</key>
  <string>${name}</string>
  <key>CFBundleDisplayName</key>
  <string>${name}</string>
  <key>CFBundlePackageType</key>
  <string>APPL</string>
  <key>CFBundleShortVersionString</key>
  <string>1.0</string>
  <key>CFBundleVersion</key>
  <string>1</string>
  <key>LSMinimumSystemVersion</key>
  <string>11.0</string>
  <key>LSUIElement</key>
  <false/>
</dict>
</plist>`;
}

function launcherScript({ appDir, nodeBin }) {
  return `#!/bin/bash
# REALM Console.app launcher (generated by installer).
# 退出本 app 会停止本地服务。
set -euo pipefail
APP_DIR="${appDir}"
NODE_BIN="${nodeBin}"
if [[ ! -x "$NODE_BIN" ]]; then
  NODE_BIN="$(command -v node || true)"
fi
if [[ ! -x "$NODE_BIN" ]]; then
  NODE_BIN="$HOME/.realm/node/bin/node"
fi
if [[ ! -x "$NODE_BIN" ]]; then
  osascript -e 'display alert "REALM Console" message "找不到 Node.js。请先运行安装命令，或手动安装 Node 22+。"' >&2
  exit 1
fi
cd "$APP_DIR" || exit 1
exec "$NODE_BIN" launcher/realm-console.mjs
`;
}

export async function createMacosConsoleApp(options = {}) {
  const appDir = resolve(options.appDir ?? join(homedir(), ".realm", "app"));
  const nodeBin = options.nodeBin ?? "$(command -v node)";
  const appName = options.appName ?? "REALM Console";
  const bundleId = options.bundleId ?? "com.silveraurora.realm.console";
  const applicationsDir = resolve(options.applicationsDir ?? join(homedir(), "Applications"));
  const appPath = join(applicationsDir, `${appName}.app`);
  const contentsDir = join(appPath, "Contents");
  const macosDir = join(contentsDir, "MacOS");
  const resourcesDir = join(contentsDir, "Resources");
  const executableName = "REALM Console";
  const executablePath = join(macosDir, executableName);

  await mkdir(macosDir, { recursive: true });
  await mkdir(resourcesDir, { recursive: true });

  await writeFile(
    join(contentsDir, "Info.plist"),
    plist({ bundleId, name: appName, executable: executableName }),
    "utf8",
  );

  await writeFile(
    executablePath,
    launcherScript({ appDir, nodeBin }),
    { mode: 0o755 },
  );

  // 如果没有自定义图标，使用系统默认 Terminal 图标（通过 LSApplicationCategoryType 引导）。
  // 这里放一个空 icns 占位，系统会 fallback 到通用 app 图标。
  const icnsPath = join(resourcesDir, "AppIcon.icns");
  if (!existsSync(icnsPath)) {
    await writeFile(icnsPath, Buffer.alloc(0));
  }

  return { appPath, executablePath };
}

const isDirectRun = process.argv[1]
  && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isDirectRun) {
  const appDir = process.argv[2] ? resolve(process.argv[2]) : undefined;
  const nodeBin = process.argv[3] || undefined;
  const result = await createMacosConsoleApp({ appDir, nodeBin });
  console.log(`created ${result.appPath}`);
}
