export const UI_LANGUAGES = ["zh-CN", "en", "ja"] as const;

export type UiLanguage = (typeof UI_LANGUAGES)[number];

export const DEFAULT_UI_LANGUAGE: UiLanguage = "zh-CN";

/** 非法/缺失语言值一律按默认中文处理。 */
export function normalizeUiLanguage(value: unknown): UiLanguage {
  return typeof value === "string"
    && (UI_LANGUAGES as readonly string[]).includes(value)
    ? (value as UiLanguage)
    : DEFAULT_UI_LANGUAGE;
}

type MessageTable = Record<UiLanguage, string>;

function interpolate(template: string, params?: Record<string, string>): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    params[key] !== undefined && params[key] !== "" ? params[key] : match);
}

const M = (zh: string, en: string, ja: string): MessageTable => ({
  "zh-CN": zh,
  en,
  ja,
});

