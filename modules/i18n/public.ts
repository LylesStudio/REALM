/** 批次注册表：按面板分批维护，统一并入主表（契约测试覆盖全部 key）。 */
for (const [key, table] of Object.entries({ ...SETTINGS_MESSAGES, ...PANEL_MESSAGES, ...DEMO_MESSAGES }) as [string, MessageTable][]) {
  if (!(key in MESSAGES)) MESSAGES[key] = table;
}

/** 界面文案查找：缺失 key 回落 zh-CN 并告警，绝不暴露裸 key。 */
export function uiText(
  key: string,
  language: UiLanguage,
  params?: Record<string, string>,
): string {
  const table = MESSAGES[key];
  if (!table) {
    console.warn(`[realm] missing ui message key: ${key}`);
    return key;
  }
  const value = table[language] ?? table[DEFAULT_UI_LANGUAGE];
  return interpolate(value, params);
}

/** 契约测试用：注册表全部 key 与三语表。 */
export function uiMessageKeys(): readonly string[] {
  return Object.keys(MESSAGES);
}

export function uiMessageTable(key: string): MessageTable | null {
  const table = MESSAGES[key];
  return table ? { ...table } : null;
}
